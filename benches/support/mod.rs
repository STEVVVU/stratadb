//! Shared deterministic workload generation for the benchmark targets.
//!
//! The key and value generators intentionally mirror the ones in the `stratadb
//! bench` CLI subcommand (`src/main.rs`), so criterion numbers and the checked-in
//! CLI benchmark artifact in `benchmarks/` describe the same workload shape.
//! They are duplicated rather than exported from the library because they are
//! test scaffolding, not part of the engine's public surface.

#![allow(dead_code)] // Each bench target uses a subset of these helpers.

/// Fixed-width sortable key, identical to the CLI benchmark's key layout.
pub fn key(number: usize) -> Vec<u8> {
    format!("key-{number:010}").into_bytes()
}

/// Deterministic pseudo-random value of `bytes` length.
///
/// Seeded per key so the byte content differs between keys (defeating any
/// accidental dedup or compression advantage) while staying reproducible across
/// runs and platforms.
pub fn value(number: usize, bytes: usize, seed: u64) -> Vec<u8> {
    let mut generator = XorShift64::new(seed ^ number as u64);
    let mut value = vec![0_u8; bytes];
    for byte in &mut value {
        *byte = u8::try_from(generator.next() & 0xff).expect("masked value fits u8");
    }
    value
}

/// A deterministic permutation of `0..count`, used for random-order access.
///
/// Generated by shuffling with the same xorshift generator so the access order
/// is identical on every run and every platform. This matters for comparability:
/// a different order changes cache and page-fault behavior.
pub fn shuffled_indices(count: usize, seed: u64) -> Vec<usize> {
    let mut indices: Vec<usize> = (0..count).collect();
    let mut generator = XorShift64::new(seed);
    for position in (1..count).rev() {
        let swap_with = usize::try_from(generator.next() % (position as u64 + 1))
            .expect("bounded index fits usize");
        indices.swap(position, swap_with);
    }
    indices
}

/// Same xorshift64 generator the CLI benchmark uses. Not cryptographic; chosen
/// because it is tiny, fast enough to stay off the measured critical path, and
/// exactly reproducible.
pub struct XorShift64(u64);

impl XorShift64 {
    pub fn new(seed: u64) -> Self {
        Self(seed.max(1))
    }

    pub fn next(&mut self) -> u64 {
        let mut value = self.0;
        value ^= value << 13;
        value ^= value >> 7;
        value ^= value << 17;
        self.0 = value;
        value
    }
}
